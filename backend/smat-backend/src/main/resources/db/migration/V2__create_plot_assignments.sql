
-- Support tenant-safe composite foreign keys
ALTER TABLE organization_memberships
    ADD CONSTRAINT uq_membership_org_id
        UNIQUE (organization_id, id);

-- Used to validate the assigning Admin belongs
-- to the same organization
ALTER TABLE organization_memberships
    ADD CONSTRAINT uq_membership_org_user
        UNIQUE (organization_id, user_id);

CREATE TABLE plot_assignments (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                  organization_id BIGINT NOT NULL,
                                  plot_id BIGINT NOT NULL,
                                  membership_id BIGINT NOT NULL,

                                  assigned_by BIGINT NOT NULL,

                                  assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                                  ended_at TIMESTAMPTZ,

                                  CONSTRAINT fk_pa_plot
                                      FOREIGN KEY (organization_id, plot_id)
                                          REFERENCES plots(organization_id, id),

                                  CONSTRAINT fk_pa_membership
                                      FOREIGN KEY (organization_id, membership_id)
                                          REFERENCES organization_memberships(
                                                                              organization_id, id
                                              ),

                                  CONSTRAINT fk_pa_assigner
                                      FOREIGN KEY (organization_id, assigned_by)
                                          REFERENCES organization_memberships(
                                                                              organization_id, user_id
                                              ),

                                  CONSTRAINT chk_pa_dates
                                      CHECK (
                                          ended_at IS NULL
                                              OR ended_at >= assigned_at
                                          )
);

-- Prevent duplicate active assignment
CREATE UNIQUE INDEX uq_pa_active
    ON plot_assignments (organization_id, plot_id, membership_id)
    WHERE ended_at IS NULL;

CREATE INDEX idx_pa_org_plot
    ON plot_assignments(organization_id, plot_id);

CREATE INDEX idx_pa_org_membership
    ON plot_assignments(organization_id, membership_id);
