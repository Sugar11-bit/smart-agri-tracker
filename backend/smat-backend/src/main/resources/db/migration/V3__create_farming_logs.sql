-- Đảm bảo một Planting thuộc đúng Plot
ALTER TABLE plantings
    ADD CONSTRAINT uq_planting_org_plot_id
        UNIQUE (organization_id, plot_id, id);

-- Đảm bảo Production Cycle thuộc đúng Planting
ALTER TABLE production_cycles
    ADD CONSTRAINT uq_cycle_org_planting_id
        UNIQUE (organization_id, planting_id, id);

CREATE TABLE farming_logs (

                              id BIGINT GENERATED BY DEFAULT AS IDENTITY
                                  PRIMARY KEY,

    -- UUID tạo tại Flutter
                              client_log_id UUID NOT NULL UNIQUE,

    -- Đơn vị và người thực hiện
                              organization_id BIGINT NOT NULL,
                              farmer_user_id BIGINT NOT NULL,

    -- Đối tượng canh tác
                              plot_id BIGINT NOT NULL,
                              planting_id BIGINT NOT NULL,
                              production_cycle_id BIGINT NOT NULL,

    -- Nội dung nhật ký
                              activity_type VARCHAR(40) NOT NULL,
                              activity_date DATE NOT NULL,
                              notes TEXT,

    -- Thời điểm
                              client_created_at TIMESTAMPTZ NOT NULL,
                              server_received_at TIMESTAMPTZ
                                  NOT NULL DEFAULT NOW(),

    -- Kiểm tra dữ liệu cơ bản
                              CONSTRAINT chk_farming_activity_type
                                  CHECK (
                                      activity_type IN (
                                                        'WATERING',
                                                        'FERTILIZING',
                                                        'SPRAYING',
                                                        'WEEDING',
                                                        'PRUNING',
                                                        'OTHER'
                                          )
                                      ),

    -- Người ghi phải có membership trong tổ chức
                              CONSTRAINT fk_farming_farmer
                                  FOREIGN KEY (organization_id, farmer_user_id)
                                      REFERENCES organization_memberships(
                                                                          organization_id, user_id
                                          ),

    -- Plot thuộc Organization
                              CONSTRAINT fk_farming_plot
                                  FOREIGN KEY (organization_id, plot_id)
                                      REFERENCES plots(organization_id, id),

    -- Planting thuộc Plot
                              CONSTRAINT fk_farming_planting
                                  FOREIGN KEY (
                                               organization_id,
                                               plot_id,
                                               planting_id
                                      )
                                      REFERENCES plantings(
                                                           organization_id,
                                                           plot_id,
                                                           id
                                          ),

    -- Production Cycle thuộc Planting
                              CONSTRAINT fk_farming_cycle
                                  FOREIGN KEY (
                                               organization_id,
                                               planting_id,
                                               production_cycle_id
                                      )
                                      REFERENCES production_cycles(
                                                                   organization_id,
                                                                   planting_id,
                                                                   id
                                          )
);

CREATE INDEX idx_farming_logs_plot
    ON farming_logs(organization_id, plot_id);

CREATE INDEX idx_farming_logs_cycle
    ON farming_logs(organization_id, production_cycle_id);

CREATE INDEX idx_farming_logs_farmer
    ON farming_logs(organization_id, farmer_user_id);

CREATE INDEX idx_farming_logs_activity_date
    ON farming_logs(activity_date);