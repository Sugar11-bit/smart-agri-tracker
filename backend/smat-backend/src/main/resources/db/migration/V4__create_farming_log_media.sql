
-- Bảng ảnh minh chứng
CREATE TABLE farming_log_photos (
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY
                                        PRIMARY KEY,

                                    farming_log_id BIGINT NOT NULL
                                        REFERENCES farming_logs(id)
                                            ON DELETE RESTRICT,

                                    client_photo_id UUID NOT NULL UNIQUE,

                                    file_name VARCHAR(255) NOT NULL UNIQUE,
                                    content_type VARCHAR(50) NOT NULL,
                                    file_size BIGINT NOT NULL
                                        CHECK (file_size > 0 AND file_size <= 5242880),

                                    sha256 CHAR(64) NOT NULL,

                                    server_received_at TIMESTAMPTZ NOT NULL
                                        DEFAULT NOW()
);

CREATE INDEX idx_farming_log_photos_log
    ON farming_log_photos(farming_log_id);


-- Mỗi nhật ký có tối đa một GPS
CREATE TABLE farming_log_locations (
                                       farming_log_id BIGINT PRIMARY KEY
                                           REFERENCES farming_logs(id)
                                               ON DELETE RESTRICT,

                                       latitude DOUBLE PRECISION NOT NULL
                                           CHECK (latitude BETWEEN -90 AND 90),

                                       longitude DOUBLE PRECISION NOT NULL
                                           CHECK (longitude BETWEEN -180 AND 180),

                                       accuracy_meters DOUBLE PRECISION NOT NULL
                                           CHECK (
                                               accuracy_meters >= 0
                                                   AND accuracy_meters < 1000000
                                               ),

                                       captured_at TIMESTAMPTZ NOT NULL,

                                       server_received_at TIMESTAMPTZ NOT NULL
                                           DEFAULT NOW()
);
