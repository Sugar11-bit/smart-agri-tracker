-- Chỉ sử dụng nếu database chưa áp dụng V1 này.

CREATE TABLE organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_code VARCHAR(40) NOT NULL UNIQUE,
    org_name VARCHAR(150) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'SUSPENDED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(60) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE organization_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL
        REFERENCES organizations(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('ADMIN', 'FARMER', 'QC')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (organization_id, user_id, role)
);

CREATE TABLE farms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL
        REFERENCES organizations(id),
    farm_code VARCHAR(40) NOT NULL,
    farm_name VARCHAR(150) NOT NULL,
    address_text TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (organization_id, farm_code),
    UNIQUE (organization_id, id)
);

CREATE TABLE plots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    farm_id BIGINT NOT NULL,
    plot_code VARCHAR(40) NOT NULL,
    plot_name VARCHAR(150) NOT NULL,
    area_hectares NUMERIC(12,4) NOT NULL
        CHECK (area_hectares > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    FOREIGN KEY (organization_id, farm_id)
        REFERENCES farms(organization_id, id),
    UNIQUE (organization_id, plot_code),
    UNIQUE (organization_id, id)
);

CREATE TABLE crop_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_code VARCHAR(40) NOT NULL UNIQUE,
    crop_name VARCHAR(100) NOT NULL,
    life_cycle VARCHAR(20) NOT NULL
        CHECK (life_cycle IN (
            'PERENNIAL', 'ANNUAL', 'OTHER'
        ))
);

CREATE TABLE crop_varieties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_type_id BIGINT NOT NULL REFERENCES crop_types(id),
    variety_name VARCHAR(120) NOT NULL,
    UNIQUE (crop_type_id, variety_name),
    UNIQUE (crop_type_id, id)
);

CREATE TABLE plantings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    plot_id BIGINT NOT NULL,
    crop_type_id BIGINT NOT NULL REFERENCES crop_types(id),
    variety_id BIGINT,
    planting_code VARCHAR(40) NOT NULL,
    planted_at DATE,
    ended_at DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'PLANNED'
        CHECK (status IN (
            'PLANNED', 'ACTIVE', 'ENDED', 'CANCELLED'
        )),
    FOREIGN KEY (organization_id, plot_id)
        REFERENCES plots(organization_id, id),
    FOREIGN KEY (crop_type_id, variety_id)
        REFERENCES crop_varieties(crop_type_id, id),
    CHECK (
        ended_at IS NULL OR
        (planted_at IS NOT NULL AND ended_at >= planted_at)
    ),
    UNIQUE (organization_id, planting_code),
    UNIQUE (organization_id, id)
);

CREATE TABLE production_cycles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    planting_id BIGINT NOT NULL,
    cycle_code VARCHAR(40) NOT NULL,
    cycle_year INTEGER
        CHECK (cycle_year BETWEEN 1900 AND 2200),
    start_date DATE NOT NULL,
    end_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN (
            'DRAFT', 'ACTIVE', 'COMPLETED', 'CANCELLED'
        )),
    FOREIGN KEY (organization_id, planting_id)
        REFERENCES plantings(organization_id, id),
    CHECK (end_date IS NULL OR end_date >= start_date),
    UNIQUE (organization_id, cycle_code),
    UNIQUE (organization_id, id)
);

CREATE INDEX idx_memberships_user
    ON organization_memberships(user_id);

CREATE INDEX idx_farms_organization
    ON farms(organization_id);

CREATE INDEX idx_plots_farm
    ON plots(organization_id, farm_id);

CREATE INDEX idx_plantings_plot
    ON plantings(organization_id, plot_id);

CREATE INDEX idx_cycles_planting
    ON production_cycles(organization_id, planting_id);
